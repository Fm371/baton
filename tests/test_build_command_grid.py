class BuildCommandGridTest(unittest.TestCase):
    def test_every_command_line_is_as_before(self):
        keys = []
        for name in ("claude", "codex"):
            for combo in itertools.product(["", "high"], [True, False], ["acceptEdits", ""], ["workspace-write", None],
                                           [None, "p1"], [False, True], [[], ["--x", "1"]], [{}, {"A": "b"}],
                                           [[], ["/d1"]]):
                for call in [(None, None, None), (7, "/s/over.json", ["/o1", "/o2"]), (0, None, [])]:
                    keys.append((name, combo, call))
        self.assertEqual(len(keys), len(GRID))
        for (name, combo, call), (key, want) in zip(keys, GRID, strict=True):
            effort, effort_flag, perm, sandbox, profile, network, extra, env, add_dirs_pc = combo
            max_turns, settings, add_dirs = call
            pc = ProviderConfig(name=name, bin=f"/bin/{name}", extra_args=list(extra), env=dict(env),
                                settings="/s/base.json" if name == "claude" else None, permission_mode=perm,
                                effort_flag=effort_flag, add_dirs=list(add_dirs_pc), sandbox=sandbox,
                                profile=profile, network=network)
            argv, e = build_command(pc, RungSpec("m1", effort), max_turns, settings=settings, add_dirs=add_dirs)
            with self.subTest(case=key):
                self.assertEqual((tuple(argv), tuple(sorted(e.items()))), want)

    def test_an_unknown_provider_is_an_error(self):
        with self.assertRaises(ValueError):
            build_command(ProviderConfig(name="other", bin="x"), RungSpec("m"), None)


